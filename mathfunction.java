class mathfunction {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;
        System.out.println("Minimum of a & b : " + Math.min(a, b));
        System.out.println("Maximum of a & b : " + Math.max(a, b));
        System.out.println("Random Number : " + Math.random());
        System.out.println("Power Function : " + Math.pow(2, 3));
        System.out.println("Square Root : " + Math.sqrt(16));
        System.out.println("Round of any Number : " + Math.round(2.456));
        System.out.println("Ceiling of Number : " + Math.ceil(-2.35));
        System.out.println("Floor of Number : " + Math.floor(-2.35));
        System.out.println("Abs Value of Number : " + Math.abs(-2));
    }
}
